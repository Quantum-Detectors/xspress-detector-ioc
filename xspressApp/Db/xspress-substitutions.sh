#!/bin/sh
# xspress-substitutions.sh <cards>
#
# Prints the database substitutions for an xspress system with <cards> cards
# (one frame receiver / frame processor pair and two channels per card).
# The PV prefix is XSPRESS.

set -eu

if [ $# -ne 1 ] || ! [ "$1" -ge 1 ] 2>/dev/null; then
    echo "Usage: $0 <cards>" >&2
    exit 1
fi

CARDS=$1
CHANNELS=$((CARDS * 2))

# One OdinData row per card, one XspressChannel row per channel (CHAN = ADDR
# + 1) and one XspressFem row per card.
odin_data_rows() {
    i=0
    while [ "$i" -lt "$CARDS" ]; do
        printf '    { "XSPRESS", ":OD%d:", "ODN.OD", "1", "%d", "%d" }\n' \
            $((i + 1)) "$i" "$CARDS"
        i=$((i + 1))
    done
}
channel_rows() {
    i=0
    while [ "$i" -lt "$CHANNELS" ]; do
        printf '    { "XSPRESS", ":CAM:", "ODN.CAM", "%d", "%d", "%d", "1" }\n' \
            "$i" $((i + 1)) "$CHANNELS"
        i=$((i + 1))
    done
}
fem_rows() {
    i=0
    while [ "$i" -lt "$CARDS" ]; do
        printf '    { "XSPRESS", ":CAM:", "ODN.CAM", "%d", "%d", "1" }\n' \
            "$i" "$CARDS"
        i=$((i + 1))
    done
}

cat <<END
# Xspress database for $CARDS cards ($CHANNELS channels), generated by
# xspress-substitutions.sh.

# OdinData driver, all frame receiver / frame processor pairs
#  TOTAL  Number of FR/FP pairs
file "OdinDataDriver.template"
{
pattern { P, R, PORT, TIMEOUT, ADDR, TOTAL }
    { "XSPRESS", ":OD:", "ODN.OD", "1", "0", "$CARDS" }
}

# One FR/FP pair per card
file "OdinData.template"
{
pattern { P, R, PORT, TIMEOUT, ADDR, TOTAL }
$(odin_data_rows)
}

file "LiveViewPlugin.template"
{
pattern { P, R, PORT, TOTAL, GUI }
    { "XSPRESS", ":OD:", "ODN.OD", "$CARDS", "ODN.OdinData.View" }
}

file "BloscPlugin.template"
{
pattern { P, R, PORT, TOTAL, GUI }
    { "XSPRESS", ":OD:", "ODN.OD", "$CARDS", "ODN.OdinData.Blosc" }
}

file "MetaListener.template"
{
pattern { P, R, PORT }
    { "XSPRESS", ":OD:", "ODN.OD" }
}

# Detector
#  NUM_PROCESSES  Number of FR/FP pairs
#  MAX_CHANNELS   Number of channels
#  NUM_CARDS      Number of cards
file "XspressDetector.template"
{
pattern { P, R, PORT, ADDR, TIMEOUT, NUM_PROCESSES, MAX_CHANNELS, NUM_CARDS }
    { "XSPRESS", ":CAM:", "ODN.CAM", "0", "1", "$CARDS", "$CHANNELS", "$CARDS" }
}

# One row per channel
#  CHAN   Channel number (ADDR + 1)
#  TOTAL  Number of channels
file "XspressChannel.template"
{
pattern { P, R, PORT, ADDR, CHAN, TOTAL, TIMEOUT }
$(channel_rows)
}

# One row per card
#  TOTAL  Number of cards
file "XspressFem.template"
{
pattern { P, R, PORT, ADDR, TOTAL, TIMEOUT }
$(fem_rows)
}

# Live view array
file "NDStdArrays.template"
{
pattern { P, R, PORT, TYPE, FTVL, NELEMENTS, TIMEOUT, ADDR, NDARRAY_PORT, NDARRAY_ADDR, ENABLED, SCANRATE }
    { "XSPRESS", ":ARR:", "ODN.ARR", "Int32", "ULONG", "2359296", "1", "0", "ODN.CAM", "0", "0", "I/O Intr" }
}

# The IOC's own procServ (the other services are not run under procServ)
file "OdinProcServProcess.template"
{
pattern { name, APPLICATION_NAME, PROCESS_NAME }
    { "ODN", "XSPRESS", "XSPRESS" }
}

file "OdinProcServ.template"
{
pattern { name, PREFIX }
    { "ODN", "XSP-PROC-SERV" }
}
END
